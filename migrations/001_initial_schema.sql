-- Initial schema for a multi-tenant SaaS project/task application.
-- PostgreSQL 14+.

CREATE SCHEMA IF NOT EXISTS saas;

CREATE TABLE saas.tenants (
    tenant_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_slug     TEXT NOT NULL UNIQUE,
    display_name    TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tenants_slug_not_blank CHECK (length(trim(tenant_slug)) > 0),
    CONSTRAINT tenants_display_name_not_blank CHECK (length(trim(display_name)) > 0)
);

-- Exactly one settings row per tenant; tenant_id is both PK and FK (1:1).
CREATE TABLE saas.tenant_settings (
    tenant_id       BIGINT PRIMARY KEY,
    time_zone       TEXT NOT NULL DEFAULT 'UTC',
    retention_days  INTEGER NOT NULL DEFAULT 365,
    support_email   TEXT,
    CONSTRAINT tenant_settings_retention_range CHECK (retention_days BETWEEN 30 AND 3650),
    CONSTRAINT tenant_settings_timezone_not_blank CHECK (length(trim(time_zone)) > 0),
    CONSTRAINT fk_tenant_settings_tenant
        FOREIGN KEY (tenant_id) REFERENCES saas.tenants (tenant_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Users are global identities. Their access to each tenant is modeled separately.
CREATE TABLE saas.users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT NOT NULL UNIQUE,
    display_name  TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT users_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT users_display_name_not_blank CHECK (length(trim(display_name)) > 0)
);

-- Associative entity: users and tenants form an N:M relationship.
CREATE TABLE saas.tenant_memberships (
    tenant_id   BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    role        TEXT NOT NULL DEFAULT 'member',
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, user_id),
    CONSTRAINT tenant_memberships_role_check CHECK (role IN ('owner', 'admin', 'member', 'viewer')),
    CONSTRAINT fk_memberships_tenant
        FOREIGN KEY (tenant_id) REFERENCES saas.tenants (tenant_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_memberships_user
        FOREIGN KEY (user_id) REFERENCES saas.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE saas.projects (
    project_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT NOT NULL,
    project_key         TEXT NOT NULL,
    project_name        TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'active',
    created_by_user_id  BIGINT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT projects_status_check CHECK (status IN ('active', 'on_hold', 'completed', 'archived')),
    CONSTRAINT projects_key_not_blank CHECK (length(trim(project_key)) > 0),
    CONSTRAINT projects_name_not_blank CHECK (length(trim(project_name)) > 0),
    CONSTRAINT uq_projects_tenant_project UNIQUE (tenant_id, project_id),
    CONSTRAINT uq_projects_tenant_key UNIQUE (tenant_id, project_key),
    CONSTRAINT fk_projects_tenant
        FOREIGN KEY (tenant_id) REFERENCES saas.tenants (tenant_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- A project creator must be a member of the same tenant.
    CONSTRAINT fk_projects_creator_membership
        FOREIGN KEY (tenant_id, created_by_user_id)
        REFERENCES saas.tenant_memberships (tenant_id, user_id)
        ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE saas.tasks (
    task_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT NOT NULL,
    project_id        BIGINT NOT NULL,
    assignee_user_id  BIGINT,
    title             TEXT NOT NULL,
    description       TEXT,
    status            TEXT NOT NULL DEFAULT 'todo',
    priority          TEXT NOT NULL DEFAULT 'medium',
    due_date          DATE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tasks_status_check CHECK (status IN ('todo', 'in_progress', 'blocked', 'done', 'cancelled')),
    CONSTRAINT tasks_priority_check CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
    CONSTRAINT tasks_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT fk_tasks_project
        FOREIGN KEY (tenant_id, project_id)
        REFERENCES saas.projects (tenant_id, project_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- If assigned, the user must be a member of this same tenant.
    CONSTRAINT fk_tasks_assignee_membership
        FOREIGN KEY (tenant_id, assignee_user_id)
        REFERENCES saas.tenant_memberships (tenant_id, user_id)
        ON UPDATE NO ACTION ON DELETE NO ACTION
);

CREATE TABLE saas.tags (
    tag_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL,
    tag_name    TEXT NOT NULL,
    color       TEXT NOT NULL DEFAULT '#808080',
    CONSTRAINT tags_name_not_blank CHECK (length(trim(tag_name)) > 0),
    CONSTRAINT tags_color_format CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT uq_tags_tenant_tag UNIQUE (tenant_id, tag_id),
    CONSTRAINT uq_tags_tenant_name UNIQUE (tenant_id, tag_name),
    CONSTRAINT fk_tags_tenant
        FOREIGN KEY (tenant_id) REFERENCES saas.tenants (tenant_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Associative entity for the projects<->tags N:M relationship.
CREATE TABLE saas.project_tags (
    tenant_id   BIGINT NOT NULL,
    project_id  BIGINT NOT NULL,
    tag_id      BIGINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tenant_id, project_id, tag_id),
    CONSTRAINT fk_project_tags_project
        FOREIGN KEY (tenant_id, project_id)
        REFERENCES saas.projects (tenant_id, project_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_project_tags_tag
        FOREIGN KEY (tenant_id, tag_id)
        REFERENCES saas.tags (tenant_id, tag_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Helpful indexes for foreign-key joins and tenant-scoped listings.
CREATE INDEX idx_memberships_user ON saas.tenant_memberships (user_id);
CREATE INDEX idx_projects_creator_membership ON saas.projects (tenant_id, created_by_user_id);
CREATE INDEX idx_tasks_project_status ON saas.tasks (tenant_id, project_id, status);
CREATE INDEX idx_tasks_assignee ON saas.tasks (tenant_id, assignee_user_id) WHERE assignee_user_id IS NOT NULL;
CREATE INDEX idx_project_tags_tag ON saas.project_tags (tenant_id, tag_id);

COMMENT ON SCHEMA saas IS 'Multi-tenant SaaS work-management demo schema';
COMMENT ON TABLE saas.tenant_memberships IS 'Associative table connecting global users to tenants and storing tenant-specific roles';
COMMENT ON TABLE saas.project_tags IS 'Associative table connecting tenant-scoped projects and tags';
